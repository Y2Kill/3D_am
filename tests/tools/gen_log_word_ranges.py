"""Generate/check diagnostic word boundaries from the pinned Unicode data."""
import argparse
import hashlib
from pathlib import Path


def render(root):
    source = root / 'third_party/unicode/17.0.0/UnicodeData.txt'
    data = source.read_bytes()
    points = []
    pending = None
    for line in data.decode('utf8').splitlines():
        parts = line.split(';')
        scalar, category = int(parts[0], 16), parts[2]
        if parts[1].endswith(', First>'):
            pending = scalar, category
            continue
        if parts[1].endswith(', Last>'):
            if pending[1][0] in 'LMN' or pending[1] == 'Pc':
                points.extend(range(pending[0], scalar + 1))
            pending = None
            continue
        if category[0] in 'LMN' or category == 'Pc':
            points.append(scalar)
    ranges = []
    for scalar in points:
        if ranges and ranges[-1][1] + 1 == scalar:
            ranges[-1] = ranges[-1][0], scalar
        else:
            ranges.append((scalar, scalar))
    text = '// Generated by tests/tools/gen_log_word_ranges.py; Unicode 17.0.0 L/M/N/Pc.\n'
    text += '// UnicodeData.txt SHA-256: ' + hashlib.sha256(data).hexdigest() + '\n'
    text += 'constexpr std::pair<char32_t,char32_t> word_ranges[] = {\n'
    text += ''.join('  {0x%X,0x%X},\n' % item for item in ranges) + '};\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    target = root / 'src/application/common/log_word_ranges.inc'
    expected = render(root)
    if arguments.check:
        if target.read_text('utf8') != expected:
            raise SystemExit('Diagnostic word ranges do not match the pinned Unicode data')
        print('Diagnostic Unicode 17.0.0 word ranges: PASS')
    else:
        target.write_text(expected, encoding='utf8', newline='\n')
