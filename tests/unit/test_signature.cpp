#include <gtest/gtest.h>

#include <cstring>
#include <string>
#include <vector>

#include "am/foundation/signature.hpp"

using am::FileKind;
using am::detect_kind;

namespace {
std::vector<std::uint8_t> v(std::initializer_list<int> b) {
  std::vector<std::uint8_t> r;
  for (int x : b) r.push_back(static_cast<std::uint8_t>(x));
  r.resize(std::max<std::size_t>(r.size(), 16), 0);
  return r;
}
std::vector<std::uint8_t> text(std::string_view s) { return {s.begin(), s.end()}; }
}  // namespace

TEST(Signature, Archives) {
  EXPECT_EQ(detect_kind(v({0x50, 0x4B, 0x03, 0x04})), FileKind::zip);
  EXPECT_EQ(detect_kind(v({0x52, 0x61, 0x72, 0x21, 0x1A, 0x07, 0x00})), FileKind::rar4);
  EXPECT_EQ(detect_kind(v({0x52, 0x61, 0x72, 0x21, 0x1A, 0x07, 0x01, 0x00})), FileKind::rar5);
  EXPECT_EQ(detect_kind(v({0x37, 0x7A, 0xBC, 0xAF, 0x27, 0x1C})), FileKind::sevenzip);
  EXPECT_TRUE(am::is_archive(FileKind::rar5));
  EXPECT_FALSE(am::is_archive(FileKind::png));
}

TEST(Signature, MacJunk) {
  EXPECT_EQ(detect_kind(v({0x00, 0x05, 0x16, 0x07, 0x00, 0x02})), FileKind::apple_double);
  EXPECT_EQ(detect_kind(v({0x00, 0x00, 0x00, 0x01, 'B', 'u', 'd', '1'})), FileKind::ds_store);
}

TEST(Signature, BinaryStlWithSolidHeaderIsBinary) {
  // Many exporters write "solid" into the binary header — size check must win.
  std::vector<std::uint8_t> h(84, 0);
  std::memcpy(h.data(), "solid exported by X", 19);
  std::uint32_t n = 2;
  std::memcpy(h.data() + 80, &n, 4);
  EXPECT_EQ(detect_kind(h, 84 + 50 * 2), FileKind::stl_binary);
  EXPECT_NE(detect_kind(h, 84 + 50 * 3), FileKind::stl_binary);
}

TEST(Signature, AsciiStl) {
  EXPECT_EQ(detect_kind(text("solid cube\n  facet normal 0 0 1\n    outer loop\n"), 400), FileKind::stl_ascii);
}

TEST(Signature, ImagesAndDocs) {
  EXPECT_EQ(detect_kind(v({0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A})), FileKind::png);
  EXPECT_EQ(detect_kind(v({0xFF, 0xD8, 0xFF, 0xE0})), FileKind::jpeg);
  using namespace std::string_view_literals;  // keep embedded NUL bytes
  EXPECT_EQ(detect_kind(text("RIFF\x10\x00\x00\x00WEBPVP8 "sv)), FileKind::webp);
  EXPECT_EQ(detect_kind(text("%PDF-1.7\n")), FileKind::pdf);
  EXPECT_EQ(detect_kind(text("{\\rtf1\\ansi")), FileKind::rtf);
  EXPECT_EQ(detect_kind(text("BLENDER-v300")), FileKind::blend);
}

TEST(Signature, TextFormats) {
  EXPECT_EQ(detect_kind(text("# exported\nmtllib a.mtl\nv 0 0 0\n")), FileKind::obj_text);
  EXPECT_EQ(detect_kind(text("; generated by PrusaSlicer 2.8\nG28\n")), FileKind::gcode_text);
  EXPECT_EQ(detect_kind(text("hello world")), FileKind::unknown);
}
