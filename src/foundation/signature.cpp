bool starts(std::span<const std::uint8_t> h, std::initializer_list<std::uint8_t> sig, std::size_t off = 0) {
  if (h.size() < off + sig.size()) return false;
  return std::equal(sig.begin(), sig.end(), h.begin() + static_cast<std::ptrdiff_t>(off));
}

bool starts_text(std::span<const std::uint8_t> h, std::string_view s, std::size_t off = 0) {
  if (h.size() < off + s.size()) return false;
  return std::memcmp(h.data() + off, s.data(), s.size()) == 0;
}

bool icontains(std::span<const std::uint8_t> h, std::string_view needle) {
  if (needle.size() > h.size()) return false;
  for (std::size_t i = 0; i + needle.size() <= h.size(); ++i) {
    bool ok = true;
    for (std::size_t k = 0; k < needle.size() && ok; ++k) {
      auto c = static_cast<char>(h[i + k]);
      if (c >= 'A' && c <= 'Z') c = static_cast<char>(c - 'A' + 'a');
      ok = c == needle[k];
    }
    if (ok) return true;
  }
  return false;
}

bool looks_binary_stl(std::span<const std::uint8_t> h, std::optional<std::uint64_t> size) {
  if (!size || *size < 84 || h.size() < 84) return false;
  std::uint32_t n = 0;
  std::memcpy(&n, h.data() + 80, 4);  // little-endian on all supported targets
  return *size == 84ull + 50ull * n;
}

