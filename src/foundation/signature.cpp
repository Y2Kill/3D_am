FileKind detect_kind(std::span<const std::uint8_t> h, std::optional<std::uint64_t> size) {
  // Order matters: exact magic numbers first, heuristics last.
  if (starts(h, {0x50, 0x4B, 0x03, 0x04}) || starts(h, {0x50, 0x4B, 0x05, 0x06}) ||
      starts(h, {0x50, 0x4B, 0x07, 0x08}))
    return FileKind::zip;
  if (starts(h, {0x52, 0x61, 0x72, 0x21, 0x1A, 0x07, 0x01, 0x00})) return FileKind::rar5;
  if (starts(h, {0x52, 0x61, 0x72, 0x21, 0x1A, 0x07, 0x00})) return FileKind::rar4;
  if (starts(h, {0x37, 0x7A, 0xBC, 0xAF, 0x27, 0x1C})) return FileKind::sevenzip;
  if (starts(h, {0x1F, 0x8B})) return FileKind::gzip;
  if (starts(h, {0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00})) return FileKind::xz;
  if (starts(h, {0x42, 0x5A, 0x68})) return FileKind::bzip2;
  if (starts(h, {0x28, 0xB5, 0x2F, 0xFD})) return FileKind::zstd;
  if (starts(h, {0x00, 0x05, 0x16, 0x07})) return FileKind::apple_double;
  if (starts(h, {0x00, 0x00, 0x00, 0x01, 0x42, 0x75, 0x64, 0x31})) return FileKind::ds_store;
  if (starts(h, {0xD0, 0xCF, 0x11, 0xE0, 0xA1, 0xB1, 0x1A, 0xE1})) return FileKind::ole_compound;
  if (starts(h, {0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A})) return FileKind::png;
  if (starts(h, {0xFF, 0xD8, 0xFF})) return FileKind::jpeg;
  if (starts_text(h, "GIF87a") || starts_text(h, "GIF89a")) return FileKind::gif;
  if (starts_text(h, "RIFF") && starts_text(h, "WEBP", 8)) return FileKind::webp;
  if (starts_text(h, "BM") && h.size() >= 14) return FileKind::bmp;
  if (starts(h, {0x49, 0x49, 0x2A, 0x00}) || starts(h, {0x4D, 0x4D, 0x00, 0x2A})) return FileKind::tiff;
  if (starts_text(h, "8BPS")) return FileKind::psd;
  if (starts_text(h, "%PDF-")) return FileKind::pdf;
  if (starts_text(h, "{\\rtf")) return FileKind::rtf;
  if (starts_text(h, "BLENDER")) return FileKind::blend;
  if (starts(h, {0x12, 0xFD, 0x00, 0x07}) || starts(h, {0x86, 0x00, 0xFD, 0x12})) return FileKind::ctb;

  // Binary STL is checked by size BEFORE the ASCII test: many binary STL
  // exporters write "solid ..." into the 80-byte header.
  if (looks_binary_stl(h, size)) return FileKind::stl_binary;
  if (starts_text(h, "solid") && icontains(h, "facet")) return FileKind::stl_ascii;
  if (starts_text(h, "solid") && h.size() < 96) return FileKind::stl_ascii;  // tiny file, best effort

  // Text heuristics for OBJ / G-code (first non-comment tokens).
  if (icontains(h, "\nv ") || starts_text(h, "v ") || icontains(h, "\nmtllib ") || starts_text(h, "mtllib "))
    return FileKind::obj_text;
  if (icontains(h, "\ng1 ") || icontains(h, "\ng0 ") || starts_text(h, "G1 ") || starts_text(h, "G28") ||
      icontains(h, "generated by prusaslicer") || icontains(h, "flavor:"))
    return FileKind::gcode_text;
  return FileKind::unknown;
}

bool is_archive(FileKind k) {
  switch (k) {
    case FileKind::zip: case FileKind::rar4: case FileKind::rar5: case FileKind::sevenzip:
    case FileKind::gzip: case FileKind::xz: case FileKind::bzip2: case FileKind::zstd:
      return true;
    default:
      return false;
  }
}

std::string_view to_string(FileKind k) {
  switch (k) {
    case FileKind::unknown: return "unknown";
    case FileKind::zip: return "archive.zip";
    case FileKind::rar4: return "archive.rar4";
    case FileKind::rar5: return "archive.rar5";
    case FileKind::sevenzip: return "archive.7z";
    case FileKind::gzip: return "archive.gzip";
    case FileKind::xz: return "archive.xz";
    case FileKind::bzip2: return "archive.bzip2";
    case FileKind::zstd: return "archive.zstd";
    case FileKind::apple_double: return "os.apple_double";
    case FileKind::ds_store: return "os.ds_store";
    case FileKind::ole_compound: return "ole.compound";
    case FileKind::png: return "image.png";
    case FileKind::jpeg: return "image.jpeg";
    case FileKind::gif: return "image.gif";
    case FileKind::webp: return "image.webp";
    case FileKind::bmp: return "image.bmp";
    case FileKind::tiff: return "image.tiff";
    case FileKind::psd: return "image.psd";
    case FileKind::stl_binary: return "mesh.stl.binary";
    case FileKind::stl_ascii: return "mesh.stl.ascii";
    case FileKind::obj_text: return "mesh.obj";
    case FileKind::blend: return "project.blend";
    case FileKind::ctb: return "slice.ctb";
    case FileKind::gcode_text: return "gcode";
    case FileKind::pdf: return "doc.pdf";
    case FileKind::rtf: return "doc.rtf";
  }
  return "unknown";
}

