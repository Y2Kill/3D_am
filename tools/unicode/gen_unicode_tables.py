"""Generate deterministic Unicode 17.0.0 tables using only verified local UCD data."""

import argparse
import functools
import hashlib
import pathlib
import re
import sys

VERSION = "17.0.0"
INPUTS = ("UnicodeData.txt", "CompositionExclusions.txt", "CaseFolding.txt",
          "NormalizationTest.txt", "license.txt")
ROOT = pathlib.Path(__file__).resolve().parents[2]


def verify_inputs(directory):
    sums = {}
    for line in (directory / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  ([A-Za-z.]+)", line)
        if not match or match[2] in sums:
            raise ValueError("invalid or duplicate SHA256SUMS entry")
        sums[match[2]] = match[1]
    if set(sums) != set(INPUTS):
        raise ValueError("SHA256SUMS must cover exactly the five UCD inputs")
    for name in INPUTS:
        actual = hashlib.sha256((directory / name).read_bytes()).hexdigest()
        if actual != sums[name]:
            raise ValueError(f"SHA-256 mismatch: {name}")
    for name, prefix in (("CaseFolding.txt", "CaseFolding-"),
                         ("NormalizationTest.txt", "NormalizationTest-")):
        if f"{prefix}{VERSION}.txt" not in (directory / name).read_text(encoding="utf-8"):
            raise ValueError(f"wrong Unicode version: {name}")
    return sums


def generate(directory):
    sums = verify_inputs(directory)
    ccc, decompositions = {}, {}
    range_start = None
    for line in (directory / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        cp, combining = int(fields[0], 16), int(fields[3])
        if fields[1].endswith(", First>"):
            range_start = cp
        elif fields[1].endswith(", Last>"):
            if range_start is None:
                raise ValueError("unmatched UnicodeData range")
            if combining:
                ccc.update((value, combining) for value in range(range_start, cp + 1))
            range_start = None
        if combining:
            ccc[cp] = combining
        if fields[5] and not fields[5].startswith("<"):
            decompositions[cp] = tuple(int(value, 16) for value in fields[5].split())

    excluded = set()
    for line in (directory / "CompositionExclusions.txt").read_text(encoding="utf-8").splitlines():
        value = line.split("#", 1)[0].strip()
        if value:
            excluded.add(int(value, 16))

    @functools.lru_cache(maxsize=None)
    def expand(cp):
        if cp not in decompositions:
            return (cp,)
        return tuple(value for child in decompositions[cp] for value in expand(child))

    compositions = []
    flat, records = [], []
    for cp, direct in sorted(decompositions.items()):
        expanded = expand(cp)
        records.append((cp, len(flat), len(expanded)))
        flat.extend(expanded)
        # Full_Composition_Exclusion: explicit exclusions, singletons and
        # non-starter decompositions/composites (UAX #15 section 5).
        if (len(direct) == 2 and cp not in excluded
                and ccc.get(cp, 0) == 0 and ccc.get(direct[0], 0) == 0):
            compositions.append((*direct, cp))

    folds = {}
    for line in (directory / "CaseFolding.txt").read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        source, status, target, *_ = (part.strip() for part in body.split(";"))
        if status in ("C", "S"):
            values = target.split()
            if len(values) != 1:
                raise ValueError("simple folding must map to one scalar")
            folds[int(source, 16)] = int(values[0], 16)

    lines = [f"// Generated by tools/unicode/gen_unicode_tables.py from Unicode {VERSION} — do not edit."]
    lines.extend(f"// SHA256 {name}: {sums[name]}" for name in INPUTS)
    lines.extend([f'constexpr std::string_view kTableUnicodeVersion = "{VERSION}";',
                  "static_assert(kTableUnicodeVersion == kUnicodeVersion);", "",
                  "constexpr CombiningClass kCombiningClasses[] = {"])
    lines.extend(f"    {{0x{cp:04X}, {value}}}," for cp, value in sorted(ccc.items()))
    lines.extend(["};", "", "constexpr char32_t kDecompositionScalars[] = {"])
    for offset in range(0, len(flat), 8):
        lines.append("    " + ", ".join(f"0x{cp:04X}" for cp in flat[offset:offset + 8]) + ",")
    lines.extend(["};", "", "constexpr Decomposition kDecompositions[] = {"])
    lines.extend(f"    {{0x{cp:04X}, {offset}, {length}}}," for cp, offset, length in records)
    lines.extend(["};", "", "constexpr Composition kCompositions[] = {"])
    lines.extend(f"    {{0x{a:04X}, 0x{b:04X}, 0x{cp:04X}}}," for a, b, cp in sorted(compositions))
    lines.extend(["};", "", "constexpr CaseFold kCaseFolds[] = {"])
    lines.extend(f"    {{0x{cp:04X}, 0x{target:04X}}}," for cp, target in sorted(folds.items()))
    lines.extend(["};", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=pathlib.Path, default=ROOT / "third_party/unicode" / VERSION)
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "src/foundation/unicode_tables.inc")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = generate(args.data_dir)
        if args.check:
            if args.output.read_bytes() != data:
                raise ValueError("generated Unicode tables differ; regenerate the output")
            print(f"Unicode {VERSION} tables: PASS ({len(data)} bytes; all input hashes verified)")
        else:
            args.output.write_bytes(data)
            print(f"Unicode {VERSION} tables: generated {len(data)} bytes")
    except (OSError, ValueError) as error:
        print(f"Unicode tables: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
